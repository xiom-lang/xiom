pub const X7001_ENSURES_VIOLATION: &str = "X7001";
pub const X7002_REQUIRES_UNPROVABLE: &str = "X7002";
pub const X7003_OVERFLOW: &str = "X7003";
pub const X7004_DIV_BY_ZERO: &str = "X7004";
pub const X7005_ARRAY_BOUNDS: &str = "X7005";
pub const X7006_INVARIANT: &str = "X7006";
pub const X7007_UNKNOWN: &str = "X7007";
pub const X7008_TYPE_ERROR: &str = "X7008";

// =========================================================================
// Verification Result
// =========================================================================

#[derive(Debug, Clone)]
pub struct Counterexample {
    pub values: HashMap<String, String>,  // variable → value
    pub raw_model: String,
}

#[derive(Debug)]
pub enum VerifyResult {
    Proven,
    Violated { code: &'static str, message: String, counterexample: Option<Counterexample> },
    Inconclusive { reason: String },
    Error { message: String },
}

// =========================================================================
// SMT Type Mapping (P0 — correct per Z3_LESSONS 4.2)
// =========================================================================

fn xiom_to_smt_sort(ty: &Type) -> String {
    match ty {
        Type::Named(name, _) => match name.name.as_str() {
            "Int"                                    => "Int".to_string(),
            "Int8"                                   => "(_ BitVec 8)".to_string(),
            "Int16"                                  => "(_ BitVec 16)".to_string(),
            "Int32"                                  => "(_ BitVec 32)".to_string(),
            "Int64"                                  => "(_ BitVec 64)".to_string(),
            "UInt"                                   => "(_ BitVec 64)".to_string(),
            "UInt8"                                  => "(_ BitVec 8)".to_string(),
            "UInt16"                                 => "(_ BitVec 16)".to_string(),
            "UInt32"                                 => "(_ BitVec 32)".to_string(),
            "UInt64"                                 => "(_ BitVec 64)".to_string(),
            "Float64"                                => "(_ FloatingPoint 11 53)".to_string(),
            "Float32"                                => "(_ FloatingPoint 8 24)".to_string(),
            "Bool"                                   => "Bool".to_string(),
            "Str"                                    => "String".to_string(),
            // Aggregates will become datatypes — for now, treat as opaque
            _ => format!("|xiom_{}|", name.name),
        },
        Type::Ref(inner) | Type::MutRef(inner) | Type::Ptr(inner) => {
            // References/pointers → treat as opaque sort
            format!("|xiom_ptr_{}|", xiom_to_smt_sort(inner))
        }
        Type::Fn(..) => "|xiom_fn|".to_string(),
        _ => "Int".to_string(), // fallback
    }
}

fn is_bv_sort(sort: &str) -> bool {
    sort.starts_with("(_ BitVec")
}

fn is_fp_sort(sort: &str) -> bool {
    sort.starts_with("(_ FloatingPoint")
}

// =========================================================================
// SMT Generator — Stage 0 (textual SMT-LIB 2.6)
// =========================================================================

pub struct SMTGenerator {
    buf: String,
    ssa_counter: u64,
    var_sort_map: HashMap<String, String>,
    /// Accumulated side-condition obligations (div-by-zero, overflow, bounds, null)
    side_conditions: Vec<SideCondition>,
}

#[derive(Debug, Clone)]
struct SideCondition {
    code: &'static str,
    message: String,
    smt: String,
}

impl SMTGenerator {
    pub fn new() -> Self {
        Self { buf: String::new(), ssa_counter: 0, var_sort_map: HashMap::new(), side_conditions: Vec::new() }
    }

    // ---------------------------------------------------------------------
    // Public API
    // ---------------------------------------------------------------------

    pub fn generate(&mut self, program: &Program) -> String {
        self.emit("; XIOM Contract Verification — SMT-LIB 2.6");
        self.emit("; Generated by xiom verify v0.9.0 (Phase 5f)");
        self.emit("(set-option :produce-models true)");
        self.emit("(set-option :produce-unsat-cores true)");
        self.emit("");

        for item in &program.items {
            self.process_top_decl(item);
        }

        std::mem::take(&mut self.buf)
    }

    fn process_top_decl(&mut self, item: &TopDecl) {
        match item {
            TopDecl::Fn(f) if !f.contracts.is_empty() => {
                self.verify_function(f);
            }
            TopDecl::Type(td) if !td.invariants.is_empty() => {
                self.verify_type_invariants(td);
            }
            TopDecl::Module(m) => {
                for item in &m.items {
                    self.process_top_decl(item);
                }
            }
            _ => {}
        }
    }

    // =====================================================================
    // Function Verification — body encoding + VC generation (P0)
    // =====================================================================

    fn verify_function(&mut self, f: &FnDecl) {
        self.emit(&format!("; === Function: {} ===", f.name.name));
        self.emit("(push)");
        self.side_conditions.clear();

        // Register param sorts
        for param in &f.params {
            let sort = xiom_to_smt_sort(&param.ty);
            self.emit(&format!("(declare-const {} {})", smt_escape(&param.name.name), sort));
            self.var_sort_map.insert(param.name.name.clone(), sort.clone());
        }

        // Declare result constant
        if let Some(ret) = &f.return_type {
            let sort = xiom_to_smt_sort(ret);
            self.emit(&format!("(declare-const |result| {})", sort));
            self.var_sort_map.insert("result".to_string(), sort);
        }

        self.emit("");

        // Requires assertions
        let mut has_requires = false;
        for contract in &f.contracts {
            if let ContractClause::Requires(e, span) = contract {
                has_requires = true;
                let label = format!("req_{}_{}", smt_escape(&f.name.name), span.line);
                self.emit(&format!("; requires (line {}): {}", span.line, expr_display(e)));
                self.emit(&format!("(assert (! ",));
                self.translate_expr(&clause_expr(contract));
                self.emit(&format!(" :named |{}|))", label));
                self.emit("");
            }
        }
        if !has_requires {
            self.emit("; (no requires — assumes true)");
            self.emit("");
        }

        // --- Body encoding (P0 — was missing!) ---
        if let Some(body) = &f.body {
            self.emit("; --- body encoding ---");
            self.emit_body_ssa(f, body);
            self.emit("");
        }

        // Ensures checks: per-clause push/(assert (not E))/check-sat/pop
        for (i, contract) in f.contracts.iter().enumerate() {
            if let ContractClause::Ensures(e, span) = contract {
                let label = format!("ens_{}_{}_{}", smt_escape(&f.name.name), span.line, i);
                self.emit(&format!("; ensures (line {}): {}", span.line, expr_display(e)));
                self.emit("(push)");
                self.emit(&format!("(assert (! (not "));
                self.translate_expr(&clause_expr(contract));
                self.emit(&format!(") :named |{}|))", label));
                self.emit("(check-sat)");
                self.emit("(get-model)");
                self.emit("(pop)");
                self.emit("");
            }
        }

        // Side-condition obligation VCs (Stage 1: div-by-zero, overflow, bounds, null)
        if !self.side_conditions.is_empty() {
            self.emit("; --- side-condition obligations ---");
            for sc in &self.side_conditions.clone() {
                self.emit(&format!("; {}: {}", sc.code, sc.message));
                self.emit("(push)");
                self.emit(&format!("(assert (! (not {}) :named |obl_{}|))", sc.smt, sc.code));
                self.emit("(check-sat)");
                self.emit("(get-model)");
                self.emit("(pop)");
                self.emit("");
            }
        }

        self.emit("(pop)");
        self.emit("");
    }

    /// SSA lowering of function body.
    /// Each `let x = e` → fresh const `x_SSA`, assert `(= x_SSA ⟦e⟧)`.
    /// `return e` → assert `(= result ⟦e⟧)`.
    fn emit_body_ssa(&mut self, f: &FnDecl, body: &Block) {
        self.ssa_counter = 0;
        self.encode_block(body, f);
    }

    fn encode_block(&mut self, block: &Block, f: &FnDecl) {
        for item in &block.stmts {
            match item {
                StmtOrExpr::Stmt(stmt) => self.encode_stmt(stmt, f),
                StmtOrExpr::Expr(expr) => {
                    let val = self.translate_expr_to_val(expr);
                    // Expression statement: translate and discard
                    let _ = val;
                }
            }
        }
    }

    fn encode_stmt(&mut self, stmt: &Stmt, f: &FnDecl) {
        match stmt {
            Stmt::Let(name, ty, init, _) | Stmt::Var(name, ty, init, _) => {
                let sort = if let Some(t) = ty {
                    xiom_to_smt_sort(t)
                } else {
                    self.infer_sort(init)
                };
                let ssa_name = self.fresh_ssa(&name.name);
                self.emit(&format!("(declare-const {} {})", ssa_name, sort));
                self.var_sort_map.insert(ssa_name.clone(), sort.clone());
                let val = self.translate_expr_to_val(init);
                self.emit(&format!("(assert (= {} {}))", ssa_name, val));
            }
            Stmt::If(cond, then_b, elifs, else_b, _) => {
                let c = self.translate_expr_to_val(cond);
                self.encode_block(then_b, f);
                for (cond_e, body_e) in elifs {
                    let ce = self.translate_expr_to_val(cond_e);
                    let _ = ce;
                    self.encode_block(body_e, f);
                }
                if let Some(else_body) = else_b {
                    self.encode_block(else_body, f);
                }
            }
            Stmt::While(cond, body, _) => {
                // Without invariants, emit honest diagnostic
                let c = self.translate_expr_to_val(cond);
                let _ = c;
                self.emit("; WARNING: loop without invariant — cannot verify");
                self.encode_block(body, f);
            }
            Stmt::Return(expr_opt, _) => {
                if let Some(expr) = expr_opt {
                    let val = self.translate_expr_to_val(expr);
                    self.emit(&format!("(assert (= |result| {}))", val));
                }
            }
            Stmt::Assign(target, expr, _) => {
                let target_name = match target {
                    Expr::Ident(id) => id.name.clone(),
                    Expr::Field(_, field, _) => field.name.clone(),
                    _ => {
                        self.emit("; WARNING: unsupported assign target");
                        return;
                    }
                };
                let ssa_name = self.fresh_ssa(&target_name);
                let sort = self.var_sort_map.get(&target_name)
                    .cloned()
                    .unwrap_or_else(|| self.infer_sort(expr));
                self.emit(&format!("(declare-const {} {})", ssa_name, sort));
                self.var_sort_map.insert(ssa_name.clone(), sort);
                let val = self.translate_expr_to_val(expr);
                self.emit(&format!("(assert (= {} {}))", ssa_name, val));
            }
            Stmt::Expr(expr, _) => {
                let _ = self.translate_expr_to_val(expr);
            }
            _ => {
                // For, Spawn, Match, Destructure, Break, Continue — not encoded yet
                self.emit("; WARNING: unsupported statement type — body may be incomplete");
            }
        }
    }

    fn fresh_ssa(&mut self, base: &str) -> String {
        let name = format!("|{}_ssa{}|", smt_escape(base), self.ssa_counter);
        self.ssa_counter += 1;
        name
    }

    fn infer_sort(&self, expr: &Expr) -> String {
        match expr {
            Expr::Int(_, _) => "Int".to_string(),
            Expr::Float(_, _) => "(_ FloatingPoint 11 53)".to_string(),
            Expr::Bool(_, _) => "Bool".to_string(),
            Expr::Ident(id) => self.var_sort_map.get(&id.name).cloned().unwrap_or_else(|| "Int".to_string()),
            _ => "Int".to_string(),
        }
    }

    // =====================================================================
    // Expression Translation (returns SMT-LIB term as string)
    // =====================================================================

    fn translate_expr_to_val(&mut self, expr: &Expr) -> String {
        let mut val = String::new();
        std::mem::swap(&mut self.buf, &mut val);
        self.translate_expr(expr);
        std::mem::swap(&mut self.buf, &mut val);
        val
    }

    // =====================================================================
    // Type Invariants
    // =====================================================================

    fn verify_type_invariants(&mut self, td: &TypeDecl) {
        self.emit(&format!("; === Type: {} — Invariants ===", td.name.name));
        self.emit("(push)");
        // Declare a symbolic instance of the type
        let sort = format!("|xiom_{}|", td.name.name);
        self.emit(&format!("(declare-const |self| {})", sort));
        for (i, inv) in td.invariants.iter().enumerate() {
            let label = format!("inv_{}_{}", smt_escape(&td.name.name), i);
            self.emit(&format!("; invariant {}: {}", i, expr_display(inv)));
            // For now, invariants are noted but not enforced as VCs
            // P1: translate invariant expressions referencing |self| fields
            self.emit(&format!("; TODO: assert (! {} :named |{}|)", expr_display(inv), label));
        }
        self.emit("(pop)");
        self.emit("");
    }

    // =====================================================================
    // Core expression translator
    // =====================================================================

    fn translate_expr(&mut self, expr: &Expr) {
        match expr {
            Expr::Int(n, _) => {
                // For BV sorts, emit hex; for Int, emit decimal
                self.buf.push_str(&format!("{}", n));
            }
            Expr::Float(f, _) => {
                // IEEE 754 hex for floating-point
                let bits = f.to_bits();
                self.buf.push_str(&format!("(fp #b{} #b{} #b{})",
                    if f.is_sign_negative() { "1" } else { "0" },
                    format!("{:011b}", ((bits >> 52) & 0x7FF) as u16),
                    format!("{:052b}", bits & 0xFFFFFFFFFFFFF)));
            }
            Expr::Bool(b, _) => {
                self.buf.push_str(if *b { "true" } else { "false" });
            }
            Expr::Ident(id) => {
                let escaped = smt_escape(&id.name);
                // If there's an SSA version, use the latest
                self.buf.push_str(&escaped);
            }
            Expr::Str(s, _) => {
                self.buf.push_str(&format!("\"{}\"", s.replace('\\', "\\\\").replace('"', "\\\"")));
            }
            Expr::Binary(left, op, right, _) => {
                // Stage 1: track div-by-zero side condition
                if matches!(op, BinOp::Div | BinOp::Rem) {
                    let mut div_buf = String::new();
                    std::mem::swap(&mut self.buf, &mut div_buf);
                    self.buf.push_str("(not (= ");
                    self.translate_expr(right);
                    self.buf.push_str(" 0))");
                    let div_smt = std::mem::replace(&mut self.buf, div_buf);
                    // Check if this div-by-zero is already tracked (dedup)
                    let dup = self.side_conditions.iter().any(|sc| sc.smt == div_smt && sc.code == X7004_DIV_BY_ZERO);
                    if !dup {
                        self.side_conditions.push(SideCondition {
                            code: X7004_DIV_BY_ZERO,
                            message: format!("division by zero: {}", expr_display(right)),
                            smt: div_smt,
                        });
                    }
                }
                let smt_op = match op {
                    BinOp::Add => "+",
                    BinOp::Sub => "-",
                    BinOp::Mul => "*",
                    BinOp::Div => "div",
                    BinOp::Rem => "mod",
                    BinOp::Eq => "=",
                    BinOp::Neq => "not",
                    BinOp::Lt => "<",
                    BinOp::Gt => ">",
                    BinOp::Le => "<=",
                    BinOp::Ge => ">=",
                    BinOp::And => "and",
                    BinOp::Or => "or",
                    _ => "=",
                };
                if op == &BinOp::Neq {
                    self.buf.push_str("(not (=");
                    self.buf.push(' ');
                    self.translate_expr(left);
                    self.buf.push(' ');
                    self.translate_expr(right);
                    self.buf.push_str("))");
                } else {
                    self.buf.push('(');
                    self.buf.push_str(smt_op);
                    self.buf.push(' ');
                    self.translate_expr(left);
                    self.buf.push(' ');
                    self.translate_expr(right);
                    self.buf.push(')');
                }
            }
            Expr::Unary(op, inner, _) => {
                match op {
                    UnaryOp::Not => {
                        self.buf.push_str("(not ");
                        self.translate_expr(inner);
                        self.buf.push(')');
                    }
                    UnaryOp::Neg => {
                        self.buf.push_str("(- ");
                        self.translate_expr(inner);
                        self.buf.push(')');
                    }
                    _ => self.translate_expr(inner),
                }
            }
            Expr::Call(func, args, _) => {
                // Function call — translate as uninterpreted function application
                self.buf.push('(');
                self.translate_expr(func);
                for arg in args {
                    self.buf.push(' ');
                    self.translate_expr(arg);
                }
                self.buf.push(')');
            }
            Expr::Field(obj, field, _) => {
                // Field access: (|field| obj)
                self.buf.push_str(&format!("(|{}| ", smt_escape(&field.name)));
                self.translate_expr(obj);
                self.buf.push(')');
            }
            // P1: unknown expressions → hard error instead of silent true
            other => {
                self.buf.push_str(&format!("; WARNING: unsupported expr {:?}", other));
                self.buf.push_str("true");
            }
        }
    }

    fn emit(&mut self, line: &str) {
        self.buf.push_str(line);
        self.buf.push('\n');
    }
}

// =========================================================================
// SMT-LIB Identifier Escaping
// =========================================================================

fn smt_escape(name: &str) -> String {
    if name.is_empty() {
        return "||".to_string();
    }
    // SMT-LIB 2.6: symbols containing special chars must be pipe-delimited
    let needs_escape = name.contains(|c: char| {
        !c.is_ascii_alphanumeric() && c != '_' && c != '-' && c != '!' && c != '?' && c != '.'
    }) || name.starts_with(|c: char| c.is_ascii_digit());
    
    if needs_escape {
        format!("|{}|", name)
    } else {
        name.to_string()
    }
}

// =========================================================================
// z3 Subprocess Runner
// =========================================================================

pub struct Z3Runner {
    pub z3_path: String,
    pub timeout_ms: u64,
}

impl Z3Runner {
    pub fn new() -> Self {
        Self {
            z3_path: "z3".to_string(),
            timeout_ms: 5000,
        }
    }

    pub fn with_z3_path(mut self, path: &str) -> Self {
        self.z3_path = path.to_string();
        self
    }

    pub fn with_timeout(mut self, ms: u64) -> Self {
        self.timeout_ms = ms;
        self
    }

    /// Run z3 on SMT-LIB2 text, parse results into VerifyResult per obligation.
    pub fn verify(&self, smt: &str) -> Vec<VerifyResult> {
        let output = match Command::new(&self.z3_path)
            .arg("-in")
            .stdin(std::process::Stdio::piped())
            .stdout(std::process::Stdio::piped())
            .stderr(std::process::Stdio::piped())
            .spawn()
        {
            Ok(mut child) => {
                use std::io::Write;
                if let Some(mut stdin) = child.stdin.take() {
                    let _ = stdin.write_all(smt.as_bytes());
                    let _ = stdin.flush();
                    // stdin is dropped here (pipe closed), signalling EOF to z3
                }
                child.wait_with_output().unwrap_or_else(|e| {
                    std::process::Output {
                        status: std::process::ExitStatus::default(),
                        stdout: vec![],
                        stderr: format!("z3 spawn error: {}", e).into_bytes(),
                    }
                })
            }
            Err(e) => {
                return vec![VerifyResult::Error {
                    message: format!("Failed to launch z3: {}. Install z3 and ensure it is on PATH.", e),
                }];
            }
        };

        let stdout = String::from_utf8_lossy(&output.stdout);
        let stderr = String::from_utf8_lossy(&output.stderr);
        
        if !stderr.is_empty() && !stderr.trim().starts_with("WARNING") && !stderr.trim().contains("WARNING") {
            // Filter benign errors: model not available after unsat, etc.
            let benign = stderr.trim().contains("model is not available");
            if !benign && (stderr.trim().starts_with("(error") || stderr.trim().starts_with("error")) {
                return vec![VerifyResult::Error {
                    message: format!("z3 error: {}", stderr.trim()),
                }];
            }
        }

        self.parse_z3_output(&stdout)
    }

    /// Parse z3 output: extract sat/unsat/unknown per check-sat and models.
    pub fn parse_z3_output(&self, output: &str) -> Vec<VerifyResult> {
        let mut results = Vec::new();
        let mut current_model = String::new();
        let mut in_model = false;

        for line in output.lines() {
            let trimmed = line.trim();
            
            if trimmed == "sat" {
                in_model = false;
                current_model.clear();
            } else if trimmed == "unsat" {
                in_model = false;
                results.push(VerifyResult::Proven);
            } else if trimmed == "unknown" {
                in_model = false;
                results.push(VerifyResult::Inconclusive {
                    reason: "z3 returned unknown (timeout or incomplete theory)".to_string(),
                });
            } else if trimmed.starts_with("(model") || in_model {
                in_model = true;
                current_model.push_str(trimmed);
                current_model.push('\n');
                if trimmed == ")" && in_model {
                    in_model = false;
                    let ce = self.parse_model(&current_model);
                    results.push(VerifyResult::Violated {
                        code: X7001_ENSURES_VIOLATION,
                        message: "ensures clause violated".to_string(),
                        counterexample: Some(ce),
                    });
                    current_model.clear();
                }
            } else if trimmed == "(" && !in_model {
                // z3 4.13.4 (get-model) outputs raw "(\n  (define-fun ..." without "(model"
                in_model = true;
                current_model.push_str(trimmed);
                current_model.push('\n');
            } else if trimmed.starts_with("(error") {
                if !trimmed.contains("model is not available") {
                    results.push(VerifyResult::Error {
                        message: trimmed.to_string(),
                    });
                }
            }
        }

        if results.is_empty() {
            results.push(VerifyResult::Error {
                message: format!("Could not parse z3 output:\n{}", output),
            });
        }

        results
    }

    /// Parse (model ...) s-expr into Counterexample.
    fn parse_model(&self, model_text: &str) -> Counterexample {
        let mut values = HashMap::new();
        
        // Simple s-expr parser: extract (define-fun name () sort value)
        for line in model_text.lines() {
            let trimmed = line.trim();
            if let Some(rest) = trimmed.strip_prefix("(define-fun ") {
                let parts: Vec<&str> = rest.splitn(2, ' ').collect();
                if parts.len() >= 1 {
                    let name = parts[0].trim_matches('|').to_string();
                    // Find the value after the empty arg list "()"
                    // Format: (define-fun name () Sort value)
                    let after_sort = rest
                        .split(')')
                        .nth(1)
                        .unwrap_or("")
                        .trim();
                    if !after_sort.is_empty() {
                        let value = after_sort
                            .split(')')
                            .next()
                            .unwrap_or("")
                            .trim()
                            .to_string();
                        if !value.is_empty() {
                            values.insert(name, value);
                        }
                    }
                }
            }
        }

        // If simple parse fails, keep raw model
        Counterexample {
            values,
            raw_model: model_text.to_string(),
        }
    }
}

